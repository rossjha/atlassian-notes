import fs from "node:fs/promises";
import path from "node:path";
import type { CustomColumnDef, Ticket } from "../shared/types.ts";
import { BOARD_CACHE_ID } from "./boardService.ts";
import type { ViewCache } from "./cache.ts";
import { isValidKey, stringifyFrontMatter } from "./frontMatter.ts";
import { atomicWrite, type NotesStore } from "./notesStore.ts";

export const TICKETS_DIR = "jira/tickets";

export const RESERVED_PROPS: readonly string[] = [
  "key", "summary", "status", "statusCategory", "type", "priority", "assignee",
  "sprint", "sprints", "labels", "url", "parent", "links", "tags",
];

export interface TicketFileContext {
  note: { data: Record<string, unknown>; parseError: string | null } | null;
  hasGroom: boolean;
  custom: Record<string, CustomColumnDef>;
}

export function tagSlug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

const ticketLink = (key: string) => `[[${TICKETS_DIR}/${key}|${key}]]`;
const collapse = (s: string) => s.replace(/\s+/g, " ").trim();

function isEmpty(v: unknown): boolean {
  return v === null || v === undefined || v === "" || (Array.isArray(v) && v.length === 0);
}

export function renderTicketFile(t: Ticket, ctx: TicketFileContext): string {
  const links = t.links ?? [];
  const sprints = t.sprints ?? [];

  const tags: string[] = [];
  const typeSlug = tagSlug(t.type);
  if (typeSlug) tags.push(`jira/${typeSlug}`);

  const customProps: Record<string, unknown> = {};
  if (ctx.note && ctx.note.parseError === null) {
    for (const [id, def] of Object.entries(ctx.custom)) {
      const value = ctx.note.data[id];
      if (typeof value !== "string") continue;
      customProps[RESERVED_PROPS.includes(id) ? `note_${id}` : id] = value;
      if (def.type === "select" && value !== "") {
        const col = tagSlug(id);
        const slug = tagSlug(value);
        if (col && slug) tags.push(`${col}/${slug}`);
      }
    }
  }

  const candidates: Record<string, unknown> = {
    key: t.key,
    summary: t.summary,
    status: t.status,
    statusCategory: t.statusCategory,
    type: t.type,
    priority: t.priority,
    assignee: t.assignee,
    sprint: t.sprint,
    sprints: sprints.map((s) => s.name),
    labels: t.labels,
    url: t.url,
    parent: t.parent ? ticketLink(t.parent.key) : null,
    links: [...new Set(links.map((l) => ticketLink(l.key)))],
    tags,
    ...customProps,
  };
  const data: Record<string, unknown> = {};
  for (const [k, v] of Object.entries(candidates)) if (!isEmpty(v)) data[k] = v;

  const lines: string[] = [];
  if (ctx.note) lines.push(`- Note: [[jira/notes/${t.key}|my note]]`);
  if (ctx.hasGroom) lines.push(`- Groom: [[jira/groom/${t.key}|groom]]`);
  if (t.parent) lines.push(`- Parent: ${ticketLink(t.parent.key)} · ${collapse(t.parent.summary)}`);
  for (const l of links) lines.push(`- ${l.type} ${ticketLink(l.key)}`);

  let body =
    "<!-- Generated by atlassian-notes from Jira; edits here are overwritten. -->\n" +
    `# ${t.key} · ${collapse(t.summary)}\n`;
  if (lines.length > 0) body += `\n${lines.join("\n")}\n`;
  return stringifyFrontMatter(data, body);
}

export async function syncTicketFiles(deps: {
  notesDir: string;
  cache: ViewCache;
  notes: NotesStore;
  getCustom: () => Promise<Record<string, CustomColumnDef>>;
  getViewIds: () => Promise<string[]>;
}): Promise<{ written: number; deleted: number }> {
  // Only current views plus the board: caches of removed views must not keep ticket files alive.
  const ids = [...(await deps.getViewIds()), BOARD_CACHE_ID];
  const { tickets, cacheFiles } = await deps.cache.allCachedTickets(ids);
  const custom = await deps.getCustom();
  const dir = path.join(path.resolve(deps.notesDir), TICKETS_DIR);
  let written = 0;
  let deleted = 0;

  const keys = new Set<string>();
  for (const [key, t] of tickets) {
    if (!isValidKey(key)) continue;
    keys.add(key);
    const note = await deps.notes.readNote(key);
    const groom = await deps.notes.readGroom(key);
    const content = renderTicketFile(t, {
      note: note ? { data: note.data, parseError: note.parseError } : null,
      hasGroom: groom !== null,
      custom,
    });
    const file = path.join(dir, `${key}.md`);
    const current = await fs.readFile(file, "utf8").catch(() => null);
    if (current === content) continue;
    await atomicWrite(file, content);
    written++;
  }

  if (cacheFiles > 0) {
    let names: string[] = [];
    try {
      names = await fs.readdir(dir);
    } catch {
      // no tickets dir yet
    }
    for (const name of names) {
      if (!name.endsWith(".md")) continue;
      const key = name.slice(0, -3);
      if (!isValidKey(key) || keys.has(key)) continue;
      await fs.rm(path.join(dir, name), { force: true });
      deleted++;
    }
  }
  return { written, deleted };
}

export interface TicketFileSyncer {
  sync(): Promise<void>;
  schedule(): void;
}

// Runs never overlap. Calls made while a run is in flight share one follow-up run.
export function createTicketFileSyncer(run: () => Promise<unknown>, debounceMs = 500): TicketFileSyncer {
  let current: Promise<void> | null = null;
  let next: Promise<void> | null = null;
  let timer: NodeJS.Timeout | null = null;

  const exec = (): Promise<void> => {
    const p = (async () => {
      try {
        await run();
      } catch (e) {
        console.error("ticket file sync failed:", e instanceof Error ? e.message : e);
      }
    })().finally(() => {
      if (current === p) current = null;
    });
    current = p;
    return p;
  };

  const sync = (): Promise<void> => {
    if (next) return next;
    if (!current) return exec();
    next = current.then(() => {
      next = null;
      return exec();
    });
    return next;
  };

  const schedule = (): void => {
    if (timer) clearTimeout(timer);
    timer = setTimeout(() => {
      timer = null;
      void sync();
    }, debounceMs);
    timer.unref();
  };

  return { sync, schedule };
}
