test("sync calls are serialised and coalesced", async () => {
  let active = 0;
  let maxActive = 0;
  let runs = 0;
  const gates: Array<() => void> = [];
  const syncer = createTicketFileSyncer(async () => {
    runs++;
    active++;
    maxActive = Math.max(maxActive, active);
    await new Promise<void>((resolve) => gates.push(resolve));
    active--;
  });
  const all = Promise.all([syncer.sync(), syncer.sync(), syncer.sync()]);
  await new Promise((r) => setTimeout(r, 10));
  assert.equal(runs, 1);
  gates[0]();
  await new Promise((r) => setTimeout(r, 10));
  assert.equal(runs, 2);
  gates[1]();
  await all;
  assert.equal(runs, 2);
  assert.equal(maxActive, 1);
});

test("sync swallows errors", async () => {
  let runs = 0;
  const syncer = createTicketFileSyncer(async () => {
    runs++;
    if (runs === 1) throw new Error("boom");
  });
  const orig = console.error;
  console.error = () => {};
  try {
    await syncer.sync();
    await syncer.sync();
  } finally {
    console.error = orig;
  }
  assert.equal(runs, 2);
});

test("schedule debounces", async () => {
  let runs = 0;
  const syncer = createTicketFileSyncer(async () => { runs++; }, 20);
  for (let i = 0; i < 5; i++) syncer.schedule();
  assert.equal(runs, 0);
  await new Promise((r) => setTimeout(r, 80));
  assert.equal(runs, 1);
});

test("sync called from a waiter's continuation never overlaps runs", async () => {
  let active = 0;
  let maxActive = 0;
  let runs = 0;
  const syncer = createTicketFileSyncer(async () => {
    runs++;
    active++;
    maxActive = Math.max(maxActive, active);
    await new Promise((r) => setTimeout(r, 10));
    active--;
  });
  const first = syncer.sync().then(() => syncer.sync());
  const second = syncer.sync();
  await Promise.all([first, second]);
  assert.equal(maxActive, 1);
  assert.ok(runs >= 2);
});
