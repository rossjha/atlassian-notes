import { test, beforeEach, afterEach } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import type { CustomColumnDef, Ticket } from "../src/shared/types.ts";
import { NotesStore } from "../src/server/notesStore.ts";
import { ViewCache } from "../src/server/cache.ts";
import { parseFrontMatter } from "../src/server/frontMatter.ts";
import { createTicketFileSyncer, renderTicketFile, syncTicketFiles, tagSlug } from "../src/server/ticketFiles.ts";

let dir: string;
let cache: ViewCache;
let notes: NotesStore;

beforeEach(async () => {
  dir = await fs.mkdtemp(path.join(os.tmpdir(), "tickets-"));
  cache = new ViewCache(dir);
  notes = new NotesStore(dir);
});
afterEach(async () => {
  await fs.rm(dir, { recursive: true, force: true });
});

function ticket(key: string, over: Partial<Ticket> = {}): Ticket {
  return {
    id: "1",
    key,
    url: `https://example.atlassian.net/browse/${key}`,
    summary: "Define step",
    status: "In Progress",
    statusCategory: "indeterminate",
    type: "Story",
    priority: "High",
    assignee: "Sam Example",
    reporter: null,
    storyPoints: null,
    parent: null,
    labels: [],
    sprint: null,
    updated: "2026-01-01T00:00:00Z",
    ...over,
  };
}

const noCtx = { note: null, hasGroom: false, custom: {} };
const getCustom = async (): Promise<Record<string, CustomColumnDef>> => ({});
const T1 = "2026-10-24T10:00:00.000Z";
const getViewIds = async () => ["v1"];
const deps = () => ({ notesDir: dir, cache, notes, getCustom, getViewIds });
const tpath = (k: string) => path.join(dir, "jira/tickets", `${k}.md`);

test("tagSlug", () => {
  assert.equal(tagSlug("Tech debt!"), "tech-debt");
  assert.equal(tagSlug("--A  B--"), "a-b");
  assert.equal(tagSlug("???"), "");
});

test("renders front matter, tags and body", () => {
  const t = ticket("AAA-101", {
    parent: { key: "AAA-12", summary: "Epic one" },
    links: [{ type: "blocks", direction: "outward", key: "AAA-110" }],
    sprints: [{ name: "Sprint 12", state: "active" }],
    sprint: "Sprint 12",
    labels: ["x"],
    components: ["API"],
  });
  const custom: Record<string, CustomColumnDef> = {
    category: { label: "Category", type: "select", options: { "Tech debt": "amber" } },
  };
  const out = renderTicketFile(t, {
    note: { data: { category: "Tech debt" }, parseError: null },
    hasGroom: true,
    custom,
  });
  assert.equal(
    out,
    `---
key: AAA-101
summary: Define step
status: In Progress
statusCategory: indeterminate
type: Story
priority: High
assignee: Sam Example
sprint: Sprint 12
sprints:
  - Sprint 12
labels:
  - x
components:
  - API
url: https://example.atlassian.net/browse/AAA-101
parent: "[[jira/tickets/AAA-12|AAA-12]]"
links:
  - "[[jira/tickets/AAA-110|AAA-110]]"
tags:
  - jira/story
  - category/tech-debt
category: Tech debt
---
<!-- Generated by atlassian-notes from Jira; edits here are overwritten. -->
# AAA-101 · Define step

- Note: [[jira/notes/AAA-101|my note]]
- Groom: [[jira/groom/AAA-101|groom]]
- Parent: [[jira/tickets/AAA-12|AAA-12]] · Epic one
- blocks [[jira/tickets/AAA-110|AAA-110]]
`,
  );
});

test("omits note and groom lines when absent", () => {
  const out = renderTicketFile(ticket("AAA-1"), noCtx);
  assert.ok(!out.includes("- Note:"));
  assert.ok(!out.includes("- Groom:"));
  assert.ok(out.endsWith("# AAA-1 · Define step\n"));
});

test("renders a ticket cached before links/sprints existed", () => {
  const out = renderTicketFile(ticket("AAA-1"), noCtx);
  assert.ok(!out.includes("links:"));
  assert.ok(!out.includes("sprints:"));
});

test("reserved custom column id is namespaced", () => {
  const out = renderTicketFile(ticket("AAA-1"), {
    note: { data: { status: "mine" }, parseError: null },
    hasGroom: false,
    custom: { status: { label: "Status", type: "text" } },
  });
  const data = parseFrontMatter(out).data;
  assert.equal(data.status, "In Progress");
  assert.equal(data.note_status, "mine");
});

test("note with broken front matter", async () => {
  await fs.mkdir(path.join(dir, "jira/notes"), { recursive: true });
  await fs.writeFile(path.join(dir, "jira/notes/AAA-1.md"), "---\nfoo: [\n---\nbody");
  await cache.write("v1", { fetchedAt: T1, tickets: [ticket("AAA-1")], error: null });
  await syncTicketFiles({
    ...deps(),
    getCustom: async () => ({ foo: { label: "Foo", type: "text" } }),
  });
  const out = await fs.readFile(tpath("AAA-1"), "utf8");
  assert.ok(out.includes("- Note: [[jira/notes/AAA-1|my note]]"));
  assert.ok(!("foo" in parseFrontMatter(out).data));
});

test("odd summary text", async () => {
  const summary = "a ]] b | c\n# d key: x";
  await cache.write("v1", { fetchedAt: T1, tickets: [ticket("AAA-1", { summary })], error: null });
  await syncTicketFiles(deps());
  const out = await fs.readFile(tpath("AAA-1"), "utf8");
  assert.equal(parseFrontMatter(out).data.summary, summary);
  assert.ok(out.split("\n").includes("# AAA-1 · a ]] b | c # d key: x"));
});

test("writes only changed files", async () => {
  await cache.write("v1", { fetchedAt: T1, tickets: [ticket("AAA-1")], error: null });
  assert.deepEqual(await syncTicketFiles(deps()), { written: 1, deleted: 0 });
  const m1 = (await fs.stat(tpath("AAA-1"))).mtimeMs;
  await new Promise((r) => setTimeout(r, 20));
  assert.deepEqual(await syncTicketFiles(deps()), { written: 0, deleted: 0 });
  assert.equal((await fs.stat(tpath("AAA-1"))).mtimeMs, m1);
});

test("prunes stale ticket files", async () => {
  await cache.write("v1", { fetchedAt: T1, tickets: [ticket("AAA-1")], error: null });
  await fs.mkdir(path.join(dir, "jira/tickets"), { recursive: true });
  await fs.writeFile(tpath("AAA-9"), "old");
  const r = await syncTicketFiles(deps());
  assert.equal(r.deleted, 1);
  await assert.rejects(fs.stat(tpath("AAA-9")));
});

test("does not prune when there are no cache files", async () => {
  await fs.mkdir(path.join(dir, "jira/tickets"), { recursive: true });
  await fs.writeFile(tpath("AAA-9"), "old");
  const r = await syncTicketFiles(deps());
  assert.deepEqual(r, { written: 0, deleted: 0 });
  await fs.stat(tpath("AAA-9"));
});

test("a cache that never fetched does not trigger a prune", async () => {
  await cache.write("v1", { fetchedAt: null, tickets: [], error: "offline" });
  await fs.mkdir(path.join(dir, "jira/tickets"), { recursive: true });
  await fs.writeFile(tpath("AAA-9"), "old");
  assert.deepEqual(await syncTicketFiles(deps()), { written: 0, deleted: 0 });
  await fs.stat(tpath("AAA-9"));
});

test("a stale cache for a removed view does not keep its ticket file", async () => {
  await cache.write("v1", { fetchedAt: T1, tickets: [ticket("AAA-1")], error: null });
  await cache.write("old-view", { fetchedAt: T1, tickets: [ticket("AAA-7")], error: null });
  await fs.mkdir(path.join(dir, "jira/tickets"), { recursive: true });
  await fs.writeFile(tpath("AAA-7"), "old");
  const r = await syncTicketFiles(deps());
  assert.equal(r.deleted, 1);
  await assert.rejects(fs.stat(tpath("AAA-7")));
  await fs.stat(tpath("AAA-1"));
});

test("duplicate key: the newest fetchedAt wins regardless of file name order", async () => {
  await cache.write("a", { fetchedAt: "2026-10-24T12:00:00.000Z", tickets: [ticket("AAA-1", { summary: "newer" })], error: null });
  await cache.write("z", { fetchedAt: "2026-10-24T09:00:00.000Z", tickets: [ticket("AAA-1", { summary: "older" })], error: null });
  await cache.write("m", { fetchedAt: null, tickets: [ticket("AAA-1", { summary: "never" })], error: null });
  await syncTicketFiles({ ...deps(), getViewIds: async () => ["z", "a", "m"] });
  assert.equal(parseFrontMatter(await fs.readFile(tpath("AAA-1"), "utf8")).data.summary, "newer");
});

test("a failing getViewIds skips the sync and prunes nothing", async () => {
  await cache.write("v1", { fetchedAt: T1, tickets: [ticket("AAA-1")], error: null });
  await fs.mkdir(path.join(dir, "jira/tickets"), { recursive: true });
  await fs.writeFile(tpath("AAA-9"), "old");
  await assert.rejects(syncTicketFiles({ ...deps(), getViewIds: async () => { throw new Error("bad yaml"); } }));
  await fs.stat(tpath("AAA-9"));
  await assert.rejects(fs.stat(tpath("AAA-1")));
});

